// life-admin/index.js — Life Admin Agent
// Handles: morning briefing, end-of-day wrap, weekly planning
// Triggers: scheduled cron + HTTP endpoint
import 'dotenv/config'
import express from 'express'
import schedule from 'node-schedule'
import { callLLM } from '../shared/llm.js'
import { readNote, readFolder, writeNote, today } from '../shared/obsidian.js'
import { notify } from '../shared/notify.js'
import { AgentState } from '../shared/agent-state.js'

const PORT = process.env.LIFE_ADMIN_PORT || 3002
const app = express()
app.use(express.json())

const state = new AgentState('life-admin', 'Briefings & planning')
state.injectControlEndpoints(app)

// ── System prompt ────────────────────────────────────────────────────────────
const SYSTEM_PROMPT = `You are the Life Admin Agent — a personal assistant embedded in an Agent OS.
You have access to the user's personal context, tasks, and goals stored in their Obsidian vault.
Your job is to help manage their daily life: morning briefings, task prioritisation, and planning.

Always be concise, action-oriented, and structured. Use markdown formatting.
Address the user by name when you know it. Be warm but efficient.`

// ── Core functions ───────────────────────────────────────────────────────────

async function morningBriefing() {
  await state.setTask('Generating Morning Briefing...')
  console.log('[Life Admin] 🌅 Running morning briefing...')

  try {
    const [context, tasks, logs] = await Promise.all([
    readNote('Notes/Personal Context.md'),
    readFolder('Tasks'),
    readNote(`Logs/${today()}.md`)
  ])

  const prompt = `
Today is ${new Date().toLocaleDateString('en-GB', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })}.

Here is my personal context:
${context}

Here are my current tasks:
${tasks || 'No tasks found.'}

${logs ? `Here is what happened earlier today:\n${logs}` : ''}

Please generate my morning briefing with:
1. **Top 3 priorities for today** (based on my goals and tasks)
2. **Quick wins** (tasks I can knock out in under 30 mins)
3. **Focus block recommendation** (what to deep work on today and when)
4. **One motivational insight** aligned with my current goals
5. **Evening reminder** (what to review at end of day)

Keep it punchy and actionable. Format in clean markdown.`

  const briefing = await callLLM(SYSTEM_PROMPT, prompt)

  const noteContent = `---
date: ${today()}
type: morning-briefing
agent: life-admin
---

# 🌅 Morning Briefing — ${new Date().toLocaleDateString('en-GB', { weekday: 'long', day: 'numeric', month: 'long' })}

${briefing}

---
*Generated by Life Admin Agent at ${new Date().toLocaleTimeString()}*`

  await writeNote(`Logs/briefings/${today()}-morning.md`, noteContent)

  notify(
    '🌅 Morning Briefing Ready',
    'Your daily briefing has been written to Obsidian. Open Logs/briefings/ to read it.'
  )

  console.log('[Life Admin] ✅ Morning briefing complete')
  await state.setIdle()
  return briefing
  } catch (err) {
    await state.setIdle()
    throw err
  }
}

