async function weeklyPlanning() {
  await state.setTask('Generating Weekly Plan...')
  console.log('[Life Admin] 📅 Running weekly planning...')

  try {
    const [context, tasks, projects] = await Promise.all([
    readNote('Notes/Personal Context.md'),
    readFolder('Tasks'),
    readFolder('Projects')
  ])

  const prompt = `
Today is ${new Date().toLocaleDateString('en-GB', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })}.

Personal context:
${context}

Current tasks:
${tasks || 'No tasks.'}

Projects:
${projects || 'No projects.'}

Please generate a weekly plan with:
1. **Theme of the week** (one sentence intention)
2. **Top goals this week** (max 5, across all life domains)
3. **Daily focus** (Mon–Fri, one main focus per day)
4. **Non-negotiables** (habits/commitments that must happen every day)
5. **What to say NO to this week** (protect focus)

Format as a clean weekly plan I can paste into Obsidian.`

  const plan = await callLLM(SYSTEM_PROMPT, prompt)

  const weekStart = today()
  const noteContent = `---
week-of: ${weekStart}
type: weekly-plan
agent: life-admin
---

# 📅 Weekly Plan — Week of ${new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}

${plan}

---
*Generated by Life Admin Agent at ${new Date().toLocaleTimeString()}*`

  await writeNote(`Tasks/weekly-plan-${weekStart}.md`, noteContent)

  notify('📅 Weekly Plan Ready', 'Your weekly plan has been written to Obsidian Tasks folder.')

  console.log('[Life Admin] ✅ Weekly plan complete')
  await state.setIdle()
  return plan
  } catch (err) {
    await state.setIdle()
    throw err
  }
}

// ── Scheduled triggers ───────────────────────────────────────────────────────

// Morning briefing — every day at 7:00am
schedule.scheduleJob('0 7 * * *', morningBriefing)

// End-of-day wrap — every day at 6:00pm
schedule.scheduleJob('0 18 * * *', endOfDayWrap)

// Weekly planning — every Monday at 8:00am
schedule.scheduleJob('0 8 * * 1', weeklyPlanning)

console.log('[Life Admin] ⏰ Scheduled: Morning briefing (7am), EOD wrap (6pm), Weekly plan (Mon 8am)')

// ── HTTP triggers ────────────────────────────────────────────────────────────

app.post('/trigger/morning-briefing', async (req, res) => {
  try {
    const result = await morningBriefing()
    res.json({ success: true, result })
  } catch (err) {
    res.status(500).json({ error: `Morning briefing failed: ${err.message}` })
  }
})

app.post('/trigger/eod-wrap', async (req, res) => {
  try {
    const result = await endOfDayWrap()
    res.json({ success: true, result })
  } catch (err) {
    res.status(500).json({ error: `EOD wrap failed: ${err.message}` })
  }
})

app.post('/trigger/weekly-plan', async (req, res) => {
  try {
    const result = await weeklyPlanning()
    res.json({ success: true, result })
  } catch (err) {
    res.status(500).json({ error: `Weekly planning failed: ${err.message}` })
  }
})

// Free-form questions — orchestrator routes here
app.post('/ask', async (req, res) => {
  try {
    const { message } = req.body
    if (!message) return res.status(400).json({ error: 'No message provided' })
    const result = await callLLM(SYSTEM_PROMPT, message)
    res.json({ success: true, result })
  } catch (err) {
    res.status(500).json({ error: `Life Admin agent error: ${err.message}` })
  }
})

app.get('/health', (req, res) => {
  res.json({ agent: 'life-admin', status: state.status, currentTask: state.currentTask, time: new Date().toISOString() })
})

app.listen(PORT, '127.0.0.1', () => {
  console.log(`[Life Admin] 🚀 Agent running on port ${PORT} (localhost only)`)
})

