// researcher/index.js — Researcher Agent
// Uses Claude's server-side web search tool to do real web research and synthesis.
import 'dotenv/config'
import express from 'express'
import Anthropic from '@anthropic-ai/sdk'
import { writeNote, today } from '../shared/obsidian.js'
import { AgentState } from '../shared/agent-state.js'

const PORT = process.env.RESEARCHER_PORT || 3007
const app = express()
app.use(express.json())

const state = new AgentState('researcher', 'Web research & synthesis')
state.injectControlEndpoints(app)

const apiKey = process.env.ANTHROPIC_API_KEY
const client = apiKey ? new Anthropic({ apiKey }) : null

const SYSTEM_PROMPT = `You are the Researcher Agent in a personal Agent OS.
You answer questions by searching the live web and synthesizing what you find into a clear, well-organized answer.
Always ground factual claims in what the search actually returned — never state something as fact without a source backing it.
Be concise but thorough. Use markdown formatting with headers for multi-part answers.`

function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '').slice(0, 60) || 'query'
}

async function research(query) {
  if (!client) throw new Error('ANTHROPIC_API_KEY is not configured. Edit agents/.env to add your key.')

  let messages = [{ role: 'user', content: query }]
  let response
  for (let i = 0; i < 3; i++) {
    response = await client.messages.create({
      model: 'claude-sonnet-5',
      max_tokens: 4096,
      system: SYSTEM_PROMPT,
      tools: [{ type: 'web_search_20260209', name: 'web_search', max_uses: 5 }],
      messages
    })
    if (response.stop_reason !== 'pause_turn') break
    messages = [...messages, { role: 'assistant', content: response.content }]
  }

  const answer = response.content.filter(b => b.type === 'text').map(b => b.text).join('\n\n') || 'No answer produced.'

  const sources = []
  for (const block of response.content) {
    if (block.type === 'web_search_tool_result' && Array.isArray(block.content)) {
      for (const item of block.content) {
        if (item?.url) sources.push({ title: item.title || item.url, url: item.url })
      }
    }
  }

  return { answer, sources }
}

async function runResearch(query) {
  await state.setTask(`Researching: ${query.slice(0, 60)}`)
  try {
    const { answer, sources } = await research(query)

    const sourceList = sources.length
      ? sources.map(s => `- [${s.title}](${s.url})`).join('\n')
      : '_No distinct sources captured._'

    const noteContent = `---
date: ${today()}
type: research
agent: researcher
query: "${query.replace(/"/g, "'")}"
---

# 🔎 Research — ${query}

${answer}

## Sources
${sourceList}

---
*Generated by Researcher Agent at ${new Date().toLocaleTimeString()}*`

    await writeNote(`Logs/research/${today()}-${slugify(query)}.md`, noteContent)
    await state.setIdle()
    return { answer, sources }
  } catch (err) {
    await state.setIdle()
    throw err
  }
}

app.post('/trigger/research', async (req, res) => {
  try {
    const { message } = req.body
    if (!message) return res.status(400).json({ error: 'No query provided' })
    const result = await runResearch(message)
    res.json({ success: true, result: result.answer, sources: result.sources })
  } catch (err) {
    res.status(500).json({ error: `Research failed: ${err.message}` })
  }
})

app.post('/ask', async (req, res) => {
  try {
    const { message } = req.body
    if (!message) return res.status(400).json({ error: 'No message provided' })
    const result = await runResearch(message)
    res.json({ success: true, result: result.answer, sources: result.sources })
  } catch (err) {
    res.status(500).json({ error: `Researcher agent error: ${err.message}` })
  }
})

app.get('/health', (req, res) => {
  res.json({ agent: 'researcher', status: state.status, currentTask: state.currentTask, time: new Date().toISOString() })
})

app.listen(PORT, '127.0.0.1', () => console.log(`[Researcher] 🚀 Agent running on port ${PORT} (localhost only)`))
