// builder/index.js — Builder Agent
// Scaffolds small applications: generates real files into agents/builder/output/<project>/
// Scope: file generation only — it never runs npm install, executes scripts, or opens a shell.
import 'dotenv/config'
import express from 'express'
import fs from 'fs/promises'
import path from 'path'
import { fileURLToPath } from 'url'
import { callLLM } from '../shared/llm.js'
import { writeNote, today } from '../shared/obsidian.js'
import { AgentState } from '../shared/agent-state.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const OUTPUT_ROOT = path.join(__dirname, 'output')

const PORT = process.env.BUILDER_PORT || 3008
const app = express()
app.use(express.json())

const state = new AgentState('builder', 'Scaffolds small apps from a request')
state.injectControlEndpoints(app)

const SYSTEM_PROMPT = `You are the Builder Agent in a personal Agent OS.
When given a request, design and generate a small, complete, working application (or script) that fulfils it.
Prefer plain, dependency-light implementations (vanilla HTML/CSS/JS, or a single-file Node/Python script) unless the request clearly needs a framework.

Respond with a short plan (2-4 sentences), then the files, in EXACTLY this format, one block per file:

### PROJECT: <kebab-case-project-name>

### FILE: <relative/path/to/file.ext>
\`\`\`
<complete file content>
\`\`\`

### FILE: <relative/path/to/next-file.ext>
\`\`\`
<complete file content>
\`\`\`

Rules:
- Every file must be complete and runnable as-is — no "// rest of code..." placeholders.
- Include a short README.md file explaining what was built and how to run it.
- You are NOT executing anything — only generating files. Never claim you ran or tested the code.`

function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '').slice(0, 60) || 'project'
}

function parseBuild(text) {
  const projectMatch = text.match(/###\s*PROJECT:\s*(.+)/)
  const project = projectMatch ? slugify(projectMatch[1]) : null

  const files = []
  const fileRegex = /###\s*FILE:\s*(.+?)\n```[^\n]*\n([\s\S]*?)```/g
  let m
  while ((m = fileRegex.exec(text))) {
    files.push({ path: m[1].trim(), content: m[2] })
  }

  const plan = text.split(/###\s*PROJECT:/)[0].trim()
  return { project, files, plan }
}

async function build(request) {
  await state.setTask(`Building: ${request.slice(0, 60)}`)
  try {
    const raw = await callLLM(SYSTEM_PROMPT, request, { model: 'claude-sonnet-5', maxTokens: 8000 })
    const { project, files, plan: parsedPlan } = parseBuild(raw)
    const plan = parsedPlan || `Generated ${files.length} file(s) for: ${request}`

    if (!files.length) {
      await state.setIdle()
      return { success: false, error: 'No files were generated — the model response did not match the expected format.' }
    }

    const projectSlug = project || slugify(request)
    const projectDir = path.join(OUTPUT_ROOT, `${today()}-${projectSlug}`)

    for (const file of files) {
      const target = path.join(projectDir, file.path)
      if (!target.startsWith(projectDir)) continue // guard against path traversal
      await fs.mkdir(path.dirname(target), { recursive: true })
      await fs.writeFile(target, file.content, 'utf-8')
    }

    const summary = `---
date: ${today()}
type: build
agent: builder
request: "${request.replace(/"/g, "'")}"
---

# 🛠️ Build — ${request}

${plan}

**Output:** \`${projectDir}\`

## Files created
${files.map(f => `- \`${f.path}\``).join('\n')}

---
*Generated by Builder Agent at ${new Date().toLocaleTimeString()} — files only, nothing was executed.*`

    await writeNote(`Logs/builds/${today()}-${projectSlug}.md`, summary)
    await state.setIdle()
    return { success: true, project: projectSlug, path: projectDir, files: files.map(f => f.path), plan }
  } catch (err) {
    await state.setIdle()
    throw err
  }
}

app.post('/trigger/build', async (req, res) => {
  try {
    const { message } = req.body
    if (!message) return res.status(400).json({ error: 'No request provided' })
    const result = await build(message)
    res.json(result)
  } catch (err) {
    res.status(500).json({ error: `Build failed: ${err.message}` })
  }
})

app.post('/ask', async (req, res) => {
  try {
    const { message } = req.body
    if (!message) return res.status(400).json({ error: 'No message provided' })
    const result = await build(message)
    res.json({ success: result.success !== false, result: result.plan || result.error, ...result })
  } catch (err) {
    res.status(500).json({ error: `Builder agent error: ${err.message}` })
  }
})

app.get('/health', (req, res) => {
  res.json({ agent: 'builder', status: state.status, currentTask: state.currentTask, time: new Date().toISOString() })
})

app.listen(PORT, '127.0.0.1', () => console.log(`[Builder] 🚀 Agent running on port ${PORT} (localhost only)`))
