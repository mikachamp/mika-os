// it-security/index.js — IT Security Agent
// Audits system/dependency/secrets hygiene: npm vulnerabilities, .gitignore
// coverage, and whether secrets could end up in git. Read-only — reports and
// recommends, never modifies dependencies or git state itself.
import 'dotenv/config'
import express from 'express'
import { exec } from 'child_process'
import { promisify } from 'util'
import path from 'path'
import { fileURLToPath } from 'url'
import fs from 'fs/promises'
import schedule from 'node-schedule'
import { callLLM } from '../shared/llm.js'
import { writeNote, today } from '../shared/obsidian.js'
import { AgentState } from '../shared/agent-state.js'

const execAsync = promisify(exec)
const __dirname = path.dirname(fileURLToPath(import.meta.url))
const PROJECT_ROOT = path.join(__dirname, '..', '..')
const PROJECTS = ['agents', 'app', 'mika-os']

const PORT = process.env.IT_SECURITY_PORT || 3013
const app = express()
app.use(express.json())

const state = new AgentState('it-security', 'Dependency & secrets hygiene audits')
state.injectControlEndpoints(app)

const SYSTEM_PROMPT = `You are the IT Security Agent in a personal Agent OS.
You are given raw findings from a dependency and secrets-hygiene audit (npm audit results, .gitignore coverage).
Summarize what needs attention, ranked by real risk, in plain language. Don't pad the "everything is fine" case.
You never modify dependencies or run fixes yourself — only report and recommend. Use markdown formatting.`

async function npmAudit(project) {
  const dir = path.join(PROJECT_ROOT, project)
  try {
    // npm audit exits non-zero when vulnerabilities exist, so stdout/stderr
    // still need reading even when exec's promise rejects.
    const { stdout } = await execAsync('npm audit --json', { cwd: dir, maxBuffer: 10 * 1024 * 1024 })
    return JSON.parse(stdout)
  } catch (err) {
    if (err.stdout) {
      try { return JSON.parse(err.stdout) } catch { /* fall through */ }
    }
    return { error: err.message }
  }
}

async function checkGitignore(project) {
  const dir = path.join(PROJECT_ROOT, project)
  try {
    const content = await fs.readFile(path.join(dir, '.gitignore'), 'utf-8')
    return { exists: true, coversEnv: /(^|\n)\.env/.test(content), coversNodeModules: /node_modules/.test(content) }
  } catch {
    return { exists: false, coversEnv: false, coversNodeModules: false }
  }
}

async function runAudit() {
  await state.setTask('Running IT security audit')
  try {
    const results = {}
    for (const project of PROJECTS) {
      const [audit, gitignore] = await Promise.all([npmAudit(project), checkGitignore(project)])
      const vulns = audit.metadata?.vulnerabilities || {}
      results[project] = { vulns, gitignore, auditError: audit.error }
    }

    const findings = PROJECTS.map(project => {
      const r = results[project]
      const vulnLine = r.auditError
        ? `⚠️ npm audit could not run: ${r.auditError}`
        : `critical: ${r.vulns.critical || 0}, high: ${r.vulns.high || 0}, moderate: ${r.vulns.moderate || 0}, low: ${r.vulns.low || 0}`
      const gLine = r.gitignore.exists
        ? `.gitignore present (covers .env: ${r.gitignore.coversEnv ? '✅' : '🔴 NO'}, covers node_modules: ${r.gitignore.coversNodeModules ? '✅' : '🔴 NO'})`
        : '🔴 no .gitignore found'
      return `### ${project}\n- Vulnerabilities — ${vulnLine}\n- ${gLine}`
    }).join('\n\n')

    const totalCritHigh = PROJECTS.reduce((sum, p) => sum + (results[p].vulns.critical || 0) + (results[p].vulns.high || 0), 0)

    const summary = await callLLM(SYSTEM_PROMPT, `Audit findings:\n${findings}`).catch(
      err => `_LLM summary unavailable: ${err.message}_`
    )

    const noteContent = `---
date: ${today()}
type: security-audit
agent: it-security
critical_or_high_vulns: ${totalCritHigh}
---

# 🔐 IT Security Audit — ${today()}

${summary}

---
## Raw findings
${findings}

---
*Generated by IT Security Agent at ${new Date().toLocaleTimeString()}*`

    await writeNote(`Logs/security/it-${today()}.md`, noteContent)
    await state.setIdle()
    return { summary, results, totalCritHigh }
  } catch (err) {
    await state.setIdle()
    throw err
  }
}

// Daily audit — 4:15am (staggered from the network-security agent's 4:00am run)
schedule.scheduleJob('15 4 * * *', () => runAudit().catch(err => console.error('[IT Security] Scheduled audit failed:', err.message)))

app.post('/trigger/audit', async (req, res) => {
  try {
    const result = await runAudit()
    res.json({ success: true, result: result.summary, totalCritHigh: result.totalCritHigh })
  } catch (err) {
    res.status(500).json({ error: `IT security audit failed: ${err.message}` })
  }
})

app.post('/ask', async (req, res) => {
  try {
    const { message } = req.body
    if (!message) return res.status(400).json({ error: 'No message provided' })
    await state.setTask(`Answering: ${message.slice(0, 60)}`)
    const result = await callLLM(SYSTEM_PROMPT, message)
    await state.setIdle()
    res.json({ success: true, result })
  } catch (err) {
    await state.setIdle()
    res.status(500).json({ error: `IT Security agent error: ${err.message}` })
  }
})

app.get('/health', (req, res) => {
  res.json({ agent: 'it-security', status: state.status, currentTask: state.currentTask, time: new Date().toISOString() })
})

app.listen(PORT, '127.0.0.1', () => console.log(`[IT Security] 🚀 Agent running on port ${PORT} (localhost only)`))
