// maintenance/index.js — Maintenance Agent
// Keeps the OS's own dependencies current. Checking for updates is scheduled;
// applying them is not — it only ever runs `npm update` (respects the semver
// ranges already in package.json, so it can't jump a major version) and only
// when explicitly triggered, never on a timer.
import 'dotenv/config'
import express from 'express'
import { exec } from 'child_process'
import { promisify } from 'util'
import path from 'path'
import { fileURLToPath } from 'url'
import schedule from 'node-schedule'
import { callLLM } from '../shared/llm.js'
import { writeNote, today } from '../shared/obsidian.js'
import { AgentState } from '../shared/agent-state.js'

const execAsync = promisify(exec)
const __dirname = path.dirname(fileURLToPath(import.meta.url))
const PROJECT_ROOT = path.join(__dirname, '..', '..')
const PROJECTS = ['agents', 'app', 'mika-os']

const PORT = process.env.MAINTENANCE_PORT || 3014
const app = express()
app.use(express.json())

const state = new AgentState('maintenance', 'Keeps dependencies current')
state.injectControlEndpoints(app)

const SYSTEM_PROMPT = `You are the Maintenance Agent in a personal Agent OS.
You are given raw npm outdated/update output for the OS's own projects.
Summarize what's out of date and whether it's safe to update, in plain language.
"Safe" updates stay within the semver range in package.json; anything needing a package.json edit (a new major version) needs the user's own decision — flag it, don't recommend running it unattended. Use markdown formatting.`

async function npmOutdated(project) {
  const dir = path.join(PROJECT_ROOT, project)
  try {
    // npm outdated exits 1 when packages ARE outdated — that's not a failure here.
    const { stdout } = await execAsync('npm outdated --json', { cwd: dir, maxBuffer: 10 * 1024 * 1024 })
    return JSON.parse(stdout || '{}')
  } catch (err) {
    if (err.stdout) {
      try { return JSON.parse(err.stdout || '{}') } catch { /* fall through */ }
    }
    return {}
  }
}

async function checkUpdates() {
  await state.setTask('Checking for outdated dependencies')
  try {
    const results = {}
    for (const project of PROJECTS) {
      results[project] = await npmOutdated(project)
    }

    const findings = PROJECTS.map(project => {
      const pkgs = Object.entries(results[project])
      if (!pkgs.length) return `### ${project}\nAll dependencies up to date.`
      const rows = pkgs.map(([name, info]) =>
        `- \`${name}\`: ${info.current || 'missing'} → wanted ${info.wanted} (latest ${info.latest})${info.wanted !== info.latest ? ' — latest is a bigger jump than package.json allows' : ''}`
      ).join('\n')
      return `### ${project} (${pkgs.length} outdated)\n${rows}`
    }).join('\n\n')

    const totalOutdated = PROJECTS.reduce((sum, p) => sum + Object.keys(results[p]).length, 0)

    const summary = await callLLM(SYSTEM_PROMPT, `Outdated package findings:\n${findings}`).catch(
      err => `_LLM summary unavailable: ${err.message}_`
    )

    const noteContent = `---
date: ${today()}
type: maintenance-check
agent: maintenance
total_outdated: ${totalOutdated}
---

# 🔧 Dependency Check — ${today()}

${summary}

---
## Raw findings
${findings}

To apply safe (in-range) updates for a project, trigger this agent with:
\`POST /trigger/apply-safe-updates { "project": "agents" | "app" | "mika-os" }\`
This never runs automatically — only on explicit request.

---
*Generated by Maintenance Agent at ${new Date().toLocaleTimeString()}*`

    await writeNote(`Logs/maintenance/${today()}.md`, noteContent)
    await state.setIdle()
    return { summary, results, totalOutdated }
  } catch (err) {
    await state.setIdle()
    throw err
  }
}

async function applySafeUpdates(project) {
  if (!PROJECTS.includes(project)) throw new Error(`Unknown project "${project}". Must be one of: ${PROJECTS.join(', ')}`)
  await state.setTask(`Applying safe updates to ${project}`)
  try {
    const dir = path.join(PROJECT_ROOT, project)
    const { stdout, stderr } = await execAsync('npm update', { cwd: dir, maxBuffer: 10 * 1024 * 1024 })

    const noteContent = `---
date: ${today()}
type: maintenance-update
agent: maintenance
project: ${project}
---

# 🔧 Applied Safe Updates — ${project} — ${today()}

Ran \`npm update\` in \`${project}/\` (in-range updates only, per package.json).

\`\`\`
${stdout || '(no output)'}
${stderr || ''}
\`\`\`

---
*Generated by Maintenance Agent at ${new Date().toLocaleTimeString()}*`

    await writeNote(`Logs/maintenance/${today()}-update-${project}.md`, noteContent)
    await state.setIdle()
    return { output: stdout }
  } catch (err) {
    await state.setIdle()
    throw err
  }
}

// Weekly check (report only) — Sunday 5:00am
schedule.scheduleJob('0 5 * * 0', () => checkUpdates().catch(err => console.error('[Maintenance] Scheduled check failed:', err.message)))

app.post('/trigger/check-updates', async (req, res) => {
  try {
    const result = await checkUpdates()
    res.json({ success: true, result: result.summary, totalOutdated: result.totalOutdated })
  } catch (err) {
    res.status(500).json({ error: `Update check failed: ${err.message}` })
  }
})

app.post('/trigger/apply-safe-updates', async (req, res) => {
  try {
    const { project } = req.body
    if (!project) return res.status(400).json({ error: 'No project specified' })
    const result = await applySafeUpdates(project)
    res.json({ success: true, result: result.output })
  } catch (err) {
    res.status(500).json({ error: `Applying updates failed: ${err.message}` })
  }
})

app.post('/ask', async (req, res) => {
  try {
    const { message } = req.body
    if (!message) return res.status(400).json({ error: 'No message provided' })
    await state.setTask(`Answering: ${message.slice(0, 60)}`)
    const result = await callLLM(SYSTEM_PROMPT, message)
    await state.setIdle()
    res.json({ success: true, result })
  } catch (err) {
    await state.setIdle()
    res.status(500).json({ error: `Maintenance agent error: ${err.message}` })
  }
})

app.get('/health', (req, res) => {
  res.json({ agent: 'maintenance', status: state.status, currentTask: state.currentTask, time: new Date().toISOString() })
})

app.listen(PORT, '127.0.0.1', () => console.log(`[Maintenance] 🚀 Agent running on port ${PORT} (localhost only)`))
